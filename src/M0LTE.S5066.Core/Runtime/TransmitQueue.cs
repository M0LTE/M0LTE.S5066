using M0LTE.S5066.Core.Dts;

namespace M0LTE.S5066.Core.Runtime;

/// <summary>
/// What the MAC asks of the DTS when it wins contention (core-architecture.md 3.5 rule 4, 5.1):
/// first reject what has expired, then build one transmission.
/// </summary>
internal interface ITransmissionSource
{
    /// <summary>
    /// Rejects every queued C_PDU whose TTD is at or before now, by enqueueing primitives
    /// (C-0857, C-0864), and drops the copies a transmission starting now could no longer send
    /// within the reception window already announced (C-0353, C-1052). The MAC then drains the
    /// FIFO and re-reads the queue state.
    /// </summary>
    void ExpireDue();

    /// <summary>
    /// Builds one transmission from the queue (core-architecture.md 5.3). Called only when the
    /// queue state says something can be placed, so it never returns an empty transmission.
    /// </summary>
    Transmit Build();
}

/// <summary>
/// The DTS transmit queue and the transmission planner of core-architecture.md 5, for what phase 3
/// can send: non-ARQ C_PDUs, type 7 for normal delivery and type 8 for expedited delivery, through
/// the unconnected request tables C-9, C-11, C-13 and C-15 (C-0570, C-0575, C-0576, C-0590,
/// C-0595, C-0596, C-0610, C-0615, C-0616, C-0630, C-0635, C-0636).
/// </summary>
/// <remarks>
/// <para>
/// A C_PDU is held whole until a transmission first places it. It is segmented then, with the
/// <c>dts.max_segment_size</c> in force (C-0522 to C-0529, C-0549), into full segments and a
/// shorter last one, and its C_PDU ID is allocated then, in placement order (C-0326;
/// core-architecture.md 5.2). The type 7 and type 8 counters are separate spaces (C-0328, C-0359)
/// and both start at 0 (C-1040). Segments that do not fit wait for a later transmission; every
/// repeat is a copy of the segments cut at first placement, with only EOT and the reception window
/// stamped again (C-0352).
/// </para>
/// <para>
/// A normal C_PDU with Minimum Number of Retransmissions N is sent N+1 times (A-0081, A-0083):
/// each of its D_PDUs stays queued until it has gone that often (C-0848), in one transmission when
/// the copies fit and across several otherwise (C-0884). Expedited requests carry no count and go
/// once. Repeats follow every first copy of a transmission, one round at a time (C-0885, C-1054).
/// </para>
/// <para>
/// TTL: one timer, <c>dts.ttd</c>, runs to the earliest TTD in the queue (core-architecture.md 3.2
/// collapsing rule), or to the instant a C_PDU ID still in use is freed if a C_PDU waits for it
/// (C-0327, C-1053), whichever is sooner. At its expiry, and on entry to LINKING, every C_PDU
/// whose TTD is at or before now is dropped and rejected to the CAS (C-0857, C-0859, C-0864,
/// C-1050). Expedited requests carry no TTD and never expire.
/// </para>
/// <para>
/// MANAGEMENT and WARNING D_PDUs generated by the DTS (P3-6) are placed ahead of client data
/// (C-0297, C-1041), each sent once with no TTD.
/// </para>
/// <para>
/// ARQ data (P4-2, 16-bit family): an ARQ C_PDU for a peer with a connection is held whole, then
/// cut into segments at its first placement and sent as DATA-ONLY (type 9) D_PDUs with
/// consecutive FSNs, allocated in placement order while the peer's transmit window allows
/// (C-0502 to C-0510, C-0766, C-0775, C-0850). One ACK-ONLY (type 10) goes to each peer owed an
/// acknowledgement, merged into the first data D_PDU to that peer as DATA-ACK (type 11) when one
/// goes in the same transmission (C-0238, C-0249, C-1128). D_PDUs known or taken to have failed
/// are retransmitted ahead of first transmissions (C-0852, C-0904, C-0905). An ARQ C_PDU whose
/// TTD passes is rejected, and its unacknowledged D_PDUs go as DROP PDUs (C-0859 to C-0862, C-1124).
/// The class order is that of core-architecture.md 5.3: MANAGEMENT, WARNING, expedited, ACK-ONLY,
/// retransmissions, first transmissions of data, non-ARQ repeats.
/// RESET/WIN-RESYNC D_PDUs (P4-4) are control items after WARNING (C-1174); while a reset exchange
/// with a peer is pending its regular data is held back (C-0257), and a FULL RESET discards its
/// partly completed C_PDUs (<see cref="ResetArq"/>).
/// Not here yet: block alignment, ACK-ONLY fill, PADDING and the other acknowledgement encodings
/// (P4-3); the 8-bit family (P4-5).
/// </para>
/// </remarks>
internal sealed class TransmitQueue : ITransmissionSource
{
    /// <summary>The 12-bit C_PDU ID space of types 7 and 8 (C-0326, C-0329).</summary>
    private const int CPduIdModulus = 4096;

    /// <summary>Half seconds, the unit of EOT and the reception window (C-0104, C-0350).</summary>
    private const int HalfSecondMs = 500;

    /// <summary>The largest value of the 16-bit reception window field (C-0355).</summary>
    private const int MaxWindow = 65535;

    private static readonly TimerName TtdTimer = TimerName.Of(TimerKind.DtsTtd);

    private readonly CoreContext _context;
    private readonly IMacObserver _mac;
    private readonly List<Entry> _entries = [];
    private readonly IdSpace _normalIds = new();
    private readonly IdSpace _expeditedIds = new();
    private readonly List<ControlItem> _control = [];
    private readonly SortedDictionary<uint, int> _owedEow = new();
    private readonly List<ArqCPdu> _arq = [];
    private readonly SortedDictionary<uint, ArqLink> _links = new();
    private readonly SortedSet<uint> _sentArqPeers = new();
    private readonly List<int> _sentExpedited = [];
    private long _nextSeq;

    public TransmitQueue(CoreContext context, IMacObserver mac)
    {
        _context = context;
        _mac = mac;
    }

    /// <summary>The queued normal-delivery requests, in arrival order.</summary>
    internal IReadOnlyList<DUnidataRequest> PendingNonArq =>
        _entries.Where(e => !e.Expedited).Select(e => e.Request!).ToList();

    /// <summary>The number of queued C_PDUs with D_PDUs still owed, both deliveries.</summary>
    internal int Count => _entries.Count;

    /// <summary>The queued MANAGEMENT and WARNING D_PDUs, in arrival order (P3-6).</summary>
    internal IReadOnlyList<ControlItem> PendingControl => _control;

    /// <summary>A MANAGEMENT or WARNING D_PDU generated by the DTS (P3-6): placed ahead of client data (C-0297, C-1041).</summary>
    public void AddControl(ControlItem item)
    {
        item.Seq = _nextSeq++;
        _control.Add(item);
        _mac.QueueState(true);
    }

    /// <summary>Removes queued, unsent DTS-generated D_PDUs that match (RESET/WIN-RESYNC items a reset or a connection end makes stale, C-1175).</summary>
    public void RemoveControl(Predicate<ControlItem> match)
    {
        _control.RemoveAll(match);
        _mac.QueueState(Placeable());
    }

    /// <summary>
    /// An EOW owed to a peer (P3-6: UNRECOGNIZED-TYPE-ERROR, C-0445): it goes in the EOW field of the
    /// next D_PDU placed for that individual address, replacing EMPTY; a later one replaces an earlier
    /// one still unsent (C-1079).
    /// </summary>
    public void OweEow(uint peer, int eow) => _owedEow[peer] = eow;

    /// <summary>
    /// A non-ARQ D_UNIDATA_REQUEST: queued for type 7 D_PDUs (C-0575, C-0595). In the
    /// EXPEDITED-DATA(UNCONNECTED) state the tables queue it until the expedited data to that peer
    /// has gone (C-0615, C-0737); the planner does this by never placing it while an expedited
    /// C_PDU to the same destination is still unplaced (C-1044). A request whose TTD has already
    /// passed is rejected at once, never queued (core-architecture.md 3.2, zero-duration rule).
    /// </summary>
    public void Add(DUnidataRequest r)
    {
        if (r.Ttd <= _context.Now)
        {
            _context.Enqueue(new DUnidataRequestRejected(r.Handle, DReason.TtlExpired));
            return;
        }

        _entries.Add(new Entry(_nextSeq++, false, r.Priority, r.Dst, r.DstIsGroup, r.CPdu, r, r.Ttd, r.MinRetransmissions + 1));
        _mac.QueueState(true);
        ReconcileTimer();
    }

    /// <summary>
    /// A non-ARQ D_EXPEDITED_UNIDATA_REQUEST: queued for type 8 D_PDUs (C-0576, C-0596, C-0616,
    /// C-0656, C-0676, C-0696), sent once, no TTD. Its handle is confirmed when the transmission
    /// carrying its last D_PDU ends (C-1100).
    /// </summary>
    public void AddExpedited(DExpeditedUnidataRequest r)
    {
        _entries.Add(new Entry(_nextSeq++, true, 0, r.Dst, r.DstIsGroup, r.CPdu, null, null, 1) { Handle = r.Handle });
        _mac.QueueState(true);
        ReconcileTimer();
    }

    /// <summary>
    /// An ARQ D_UNIDATA_REQUEST for a peer with a connection (C-0653, C-0673): held whole with its
    /// TTD, so <c>dts.ttd</c> covers it (C-0857, C-1050), and placed by the planner when the peer's
    /// connection uses the 16-bit family. On a link with the 8-bit family it stays held (P4-5).
    /// </summary>
    public void AddArq(DUnidataRequest r)
    {
        if (r.Ttd <= _context.Now)
        {
            _context.Enqueue(new DUnidataRequestRejected(r.Handle, DReason.TtlExpired));
            return;
        }

        _arq.Add(new ArqCPdu(_nextSeq++, r));
        _mac.QueueState(Placeable());
        ReconcileTimer();
    }

    /// <summary>The ARQ machine of a connected 16-bit peer, or null.</summary>
    public ArqLink? LinkOf(uint peer) => _links.TryGetValue(peer, out ArqLink? l) ? l : null;

    /// <summary>
    /// A connection with the 16-bit family is made: a new ARQ machine with the initial window edges
    /// (C-0782, C-0787), and any ARQ C_PDUs already held for the peer can now be placed.
    /// </summary>
    public ArqLink OpenLink(uint peer)
    {
        var link = new ArqLink(peer);
        _links[peer] = link;
        _mac.QueueState(Placeable());
        return link;
    }

    /// <summary>
    /// The connection with the peer ended: ARQ processing stops and its state is reset (C-0652,
    /// C-0672), and every ARQ C_PDU not fully processed is rejected to the CAS, oldest first (C-0866);
    /// one already rejected for its TTD is not rejected again. <c>dts.ack_wait/&lt;peer&gt;</c> stops.
    /// </summary>
    public void RejectArq(uint peer)
    {
        _links.Remove(peer);
        _context.Timers.Cancel(AckWaitTimer(peer));
        List<ArqCPdu> gone = _arq.Where(a => a.Peer == peer).ToList();
        _arq.RemoveAll(a => a.Peer == peer);
        foreach (ArqCPdu a in gone)
        {
            if (!a.Dropped)
            {
                _context.Enqueue(new DUnidataRequestRejected(a.Request.Handle, DReason.NoConnection));
            }
        }

        _mac.QueueState(Placeable());
        ReconcileTimer();
    }

    /// <summary>
    /// The FULL RESET of the peer's ARQ machine, in either role (C-0812 to C-0814, C-0822 to C-0824):
    /// the window edges go back to their initial values and the receive buffers are flushed
    /// (<see cref="ArqLink.Reset"/>); every ARQ C_PDU to the peer that is partly completed, at least
    /// one segment given an FSN and not yet confirmed, is discarded and rejected to the CAS, oldest
    /// first, unless already rejected for its TTD (C-0813, C-0823, C-0826, C-1176); C_PDUs not yet
    /// started stay queued, to be cut afresh from the reset window. <c>dts.ack_wait/&lt;peer&gt;</c>
    /// stops, since nothing awaits an acknowledgement any more.
    /// </summary>
    public void ResetArq(uint peer)
    {
        if (!_links.TryGetValue(peer, out ArqLink? link))
        {
            return;
        }

        link.Reset();
        _context.Timers.Cancel(AckWaitTimer(peer));
        List<ArqCPdu> gone = _arq.Where(a => a.Peer == peer && a.Placed).ToList();
        _arq.RemoveAll(a => a.Peer == peer && a.Placed);
        foreach (ArqCPdu a in gone)
        {
            if (!a.Dropped)
            {
                _context.Enqueue(new DUnidataRequestRejected(a.Request.Handle, DReason.Reset));
            }
        }

        _mac.QueueState(Placeable());
        ReconcileTimer();
    }

    /// <summary>Whether ARQ C_PDUs are still held for the peer (C-1176).</summary>
    public bool HasArqFor(uint peer) => _arq.Any(a => a.Peer == peer && !a.Dropped);

    /// <summary>A reset exchange with the peer started or ended (C-0257): what can be placed may have changed.</summary>
    public void SuspensionChanged() => _mac.QueueState(Placeable());

    /// <summary>
    /// Our transmission has ended (core-architecture.md 5.7): <c>dts.ack_wait/&lt;peer&gt;</c> starts,
    /// or restarts, for each peer that had ARQ data D_PDUs in it and still has some awaiting an
    /// acknowledgement, in ascending address order (C-1120). Its value is <c>dts.ack_wait_ms</c>, or
    /// when that is unset <see cref="DerivedAckWaitMs"/>.
    /// </summary>
    public void OnTransmitDone()
    {
        foreach (uint peer in _sentArqPeers)
        {
            if (_links.TryGetValue(peer, out ArqLink? link) && link.Outstanding.Any(f => f.State == ArqFrameState.Awaiting))
            {
                _context.Timers.Start(AckWaitTimer(peer), _context.Config.Dts.AckWaitMs ?? DerivedAckWaitMs());
            }
        }

        _sentArqPeers.Clear();
    }

    /// <summary>
    /// <c>dts.ack_wait/&lt;peer&gt;</c> expired with no acknowledgement: every D_PDU to the peer still
    /// awaiting one is taken to have failed, and will be retransmitted (C-0906, C-0911, C-1120).
    /// </summary>
    public void OnAckWaitTimer(uint peer)
    {
        if (_links.TryGetValue(peer, out ArqLink? link))
        {
            foreach (ArqFrame f in link.Outstanding)
            {
                f.State = ArqFrameState.Failed;
            }
        }

        _mac.QueueState(Placeable());
    }

    /// <summary>
    /// The acknowledgement part of an ACK-ONLY or DATA-ACK from the peer (C-0679, C-0680).
    /// <list type="number">
    /// <item>An RX LWE beyond TX LWE (and no further than TX UWE + 1) acknowledges every FSN from TX
    /// LWE up to it, and TX LWE moves to it (C-0780, C-0781). One outside that range says nothing
    /// usable here; the receive side applies Test 4 first (C-0800, C-1170), so it never arrives.</item>
    /// <item>A bitmap (encoding 0) marks each FSN it covers, from RX LWE + 1 + 256 x offset
    /// (C-0233, C-0250): a set bit acknowledges it (C-0202), a clear bit means it failed (C-0205,
    /// C-0907, C-0908). Run length encoding is P4-3's: only its RX LWE is used.</item>
    /// <item>The D_PDU at RX LWE is one the peer has not received (C-0776), so it failed too (C-0908).</item>
    /// <item>Half duplex: every D_PDU awaiting an acknowledgement and sent after the last one this
    /// D_PDU acknowledges explicitly is taken to have failed (C-0910, C-1121).</item>
    /// </list>
    /// Then <c>dts.ack_wait/&lt;peer&gt;</c> stops when nothing awaits an acknowledgement, each C_PDU
    /// whose segments are all acknowledged is confirmed to the CAS in arrival order (C-1130), and
    /// <c>dts.ttd</c> follows the queue.
    /// </summary>
    public void OnAck(uint peer, int rxLwe, int encoding, int offset, ReadOnlySpan<byte> bitmap)
    {
        if (!_links.TryGetValue(peer, out ArqLink? link))
        {
            return;
        }

        SeqSpace seq = link.Seq;
        if (!seq.InArc(rxLwe, link.TxLwe, seq.Add(link.TxUwe, 1)))
        {
            return;   // cannot happen: the receive side has applied Test 4 (C-0800, C-1170)
        }

        foreach (ArqFrame f in link.Outstanding.Where(f => seq.Distance(link.TxLwe, f.Fsn) < seq.Distance(link.TxLwe, rxLwe)).ToList())
        {
            Acknowledge(link, f);
        }

        link.TxLwe = rxLwe;
        int lastExplicit = -1;   // position after RX LWE of the furthest FSN acknowledged by a set bit
        var nacked = new HashSet<int>();   // looked up only, never enumerated
        nacked.Add(rxLwe);   // RX LWE is the oldest FSN the peer has not received (C-0776, C-0907)
        if (encoding == 0)
        {
            int first = (offset * 256) + 1;
            for (int i = 0; i < bitmap.Length * 8; i++)
            {
                int fsn = seq.Add(rxLwe, first + i);
                if ((bitmap[i / 8] & (1 << (i % 8))) != 0)
                {
                    lastExplicit = first + i;
                    if (link.Outstanding.FirstOrDefault(f => f.Fsn == fsn) is ArqFrame acked)
                    {
                        Acknowledge(link, acked);
                    }
                }
                else
                {
                    nacked.Add(fsn);
                }
            }
        }

        foreach (ArqFrame f in link.Outstanding)
        {
            if (f.State == ArqFrameState.Awaiting && (nacked.Contains(f.Fsn) || seq.Distance(rxLwe, f.Fsn) > lastExplicit))
            {
                f.State = ArqFrameState.Failed;   // C-0908, C-0910
            }
        }

        if (!link.Outstanding.Any(f => f.State == ArqFrameState.Awaiting))
        {
            _context.Timers.Cancel(AckWaitTimer(peer));
        }

        foreach (ArqCPdu a in _arq.Where(a => a.Peer == peer && a.Placed && !a.HasUnplacedSegment && a.Unacked == 0).ToList())
        {
            _arq.Remove(a);
            if (!a.Dropped)
            {
                _context.Enqueue(new DUnidataRequestConfirm(a.Request.Handle));   // C-0679, C-0680, C-1130
            }
        }

        _mac.QueueState(Placeable());
        ReconcileTimer();
    }

    /// <summary>The receive side processed data from the peer and owes it an acknowledgement (C-0174, C-0242): the queue may now have something to place.</summary>
    public void AckOwed() => _mac.QueueState(Placeable());

    private static void Acknowledge(ArqLink link, ArqFrame f)
    {
        link.Outstanding.Remove(f);   // the FSN may be reused (C-0767)
        f.Owner.Unacked--;
    }

    private static TimerName AckWaitTimer(uint peer) => TimerName.ForPeer(TimerKind.DtsAckWait, peer);

    /// <summary>The handles of expedited requests whose last D_PDU went in the transmission now ending, in placement order (C-1100).</summary>
    public List<int> TakeSentExpedited()
    {
        var sent = new List<int>(_sentExpedited);
        _sentExpedited.Clear();
        return sent;
    }

    /// <summary>The ARQ requests not yet confirmed, rejected or dropped, in arrival order.</summary>
    internal IReadOnlyList<DUnidataRequest> HeldArq => _arq.Where(a => !a.Dropped).Select(a => a.Request).ToList();

    /// <summary>
    /// <c>dts.ttd</c> expired: drop and reject what has reached its TTD (C-0857, C-0864, C-1050),
    /// tell the MAC whether anything can still be placed (K-0078, K-0091), and re-arm.
    /// </summary>
    public void OnTtdTimer()
    {
        DropExpired();
        _mac.QueueState(Placeable());
        ReconcileTimer();
    }

    /// <inheritdoc/>
    public void ExpireDue()
    {
        DropExpired();
        if (Placeable())
        {
            Shape();   // drops copies that can no longer be sent in time (C-0353, C-1052)
        }

        _mac.QueueState(Placeable());
        ReconcileTimer();
    }

    /// <summary>
    /// The build algorithm of core-architecture.md 5.3 for the classes phase 3 fills, then layout
    /// (with the P3-5 round order, C-1054) and stamping (5.6). The waveform is <c>drc.default_speed</c>
    /// (C-0894, plan 6.2).
    /// </summary>
    public Transmit Build()
    {
        DropExpired();
        if (!Placeable())
        {
            throw new InvalidOperationException("the planner was asked to build with nothing it can place");
        }

        (Speed speed, long capacity) = Shape();
        (List<ControlItem> chosenControl, List<Piece> chosen) = Select(capacity);
        if (chosenControl.Count == 0 && chosen.Count == 0)
        {
            throw new InvalidOperationException("the planner chose nothing");
        }

        Transmit t = Emit(chosenControl, chosen, speed);
        _mac.QueueState(Placeable());
        ReconcileTimer();
        return t;
    }

    /// <summary>
    /// The waveform and byte capacity of a transmission starting now, after dropping the copies of
    /// every C_PDU that such a transmission could not finish sending within the reception window
    /// last announced for it (C-0353, C-1052). Dropping can change which item goes first, and so
    /// the capacity, so it repeats until nothing more is dropped.
    /// </summary>
    private (Speed Speed, long Capacity) Shape()
    {
        Speed speed = _context.Config.Drc.DefaultSpeed;
        BurstPlan shape = _context.Modem.PlanBurst(speed.Wn, speed.Interleaver, 0);
        while (true)
        {
            int first = FirstItemSize() ?? throw new InvalidOperationException("nothing can be placed");
            long capacity = Capacity(shape, first);
            long longest = shape.PreambleMs + ((capacity / shape.BytesPerBlock) * shape.BlockMs) + shape.FlushMs;
            List<Entry> late = _entries.Where(e => e.CommitEnd is long end && _context.Now + longest > end).ToList();
            if (late.Count == 0)
            {
                return (speed, capacity);
            }

            // Dropped without a rejection: the TTL has not expired, and non-ARQ has no confirmation (C-1052).
            foreach (Entry e in late)
            {
                _entries.Remove(e);
            }

            if (!Placeable())
            {
                return (speed, 0);
            }
        }
    }

    /// <summary>
    /// The size of the first D_PDU the selection would take (core-architecture.md 5.3), for the budget
    /// rule, or null when nothing can be placed. It walks the classes in the order and with the
    /// eligibility rules of <see cref="Select"/>, so a non-null answer is exactly what Select takes first.
    /// </summary>
    private int? FirstItemSize()
    {
        List<ControlItem> control = SortedControl();
        if (control.Count > 0)
        {
            return control[0].Size;
        }

        foreach (Entry e in Expedited())
        {
            if (e.HasUnplacedSegment && (e.Placed || _expeditedIds.IsFree(_context.Now)))
            {
                return SizeOf(e.NextSegmentLength(MaxSegment), true, e.Dst);
            }
        }

        foreach (ArqLink link in _links.Values)
        {
            if (link.AckOwed && !link.Suspended)   // C-0257
            {
                return AckOnlySize(link.Peer, link.AckBitmap().Length);
            }
        }

        foreach (ArqFrame f in FailedFrames())
        {
            return DataOnlySize(f.Owner.Peer, FrameLength(f));
        }

        bool idFree = _normalIds.IsFree(_context.Now);
        foreach (object c in DataCandidates())
        {
            if (c is Entry e)
            {
                if (!e.HasUnplacedSegment || HeldBehindExpedited(e.Dst, e.DstIsGroup))
                {
                    continue;
                }

                if (!e.Placed && !idFree)
                {
                    break;
                }

                return SizeOf(e.NextSegmentLength(MaxSegment), false, e.Dst);
            }

            var a = (ArqCPdu)c;
            if (!a.HasUnplacedSegment || LinkOf(a.Peer) is not ArqLink link || link.Suspended)
            {
                continue;   // C-0257: no regular data while a reset exchange is pending
            }

            if (HeldBehindExpedited(a.Peer, false) || link.WindowSize >= MaxTxWindow)
            {
                if (a.Partial)
                {
                    break;
                }

                continue;
            }

            return DataOnlySize(a.Peer, a.Dropped ? 0 : a.NextSegmentLength(MaxSegment));
        }

        foreach (Entry e in Normal())
        {
            if (e.OwedRepeat() is int seg)
            {
                return SizeOf(e.Segments![seg].Length, false, e.Dst);
            }
        }

        return null;
    }

    /// <summary>True when a transmission now could place at least one D_PDU (K-0096; core-architecture.md 4.1).</summary>
    private bool Placeable() => FirstItemSize() is not null;

    /// <summary>
    /// The queued MANAGEMENT and WARNING D_PDUs in class order, each class oldest first (C-0297,
    /// C-1041; P3-6), with their encoded sizes at the local address in force now (the address size follows the
    /// addresses, C-0133).
    /// </summary>
    private List<ControlItem> SortedControl()
    {
        foreach (ControlItem c in _control)
        {
            c.Size = DpduCodec.Encode(c.Build(Header(0, 0, c.Dst))).Length;
        }

        List<ControlItem> control = _control.ToList();
        control.Sort((a, b) => a.Class != b.Class ? a.Class.CompareTo(b.Class) : a.Seq.CompareTo(b.Seq));
        return control;
    }

    /// <summary>
    /// Chooses the D_PDUs of one transmission (core-architecture.md 5.3, C-1041): MANAGEMENT and
    /// WARNING first (C-0297; P3-6), each oldest first, a misfit skipped; then expedited first
    /// transmissions (C-0288), oldest first, a misfit skipped; then one ACK-ONLY per peer owed one,
    /// in address order (C-0370, C-1128); then retransmissions of failed ARQ D_PDUs (C-0852, C-0905,
    /// C-1132), a misfit skipped; then first transmissions of data, ARQ and non-ARQ together, by
    /// priority and age (C-0851, C-0853, C-0854), a C_PDU whose ARQ segments are partly sent first
    /// (C-0850, C-1127), a misfit stopping the class (C-0880); then the non-ARQ repeats still owed
    /// (C-0848, C-0884), by priority and age, round by round, a misfit stopping the class. A C_PDU is
    /// segmented when its first segment is taken. An ARQ data D_PDU to a peer whose ACK-ONLY was
    /// taken carries the acknowledgement instead, as DATA-ACK, when it fits in 18 bytes (C-0238,
    /// C-0249, C-1128).
    /// </summary>
    private (List<ControlItem> Control, List<Piece> Data) Select(long capacity)
    {
        var chosenControl = new List<ControlItem>();
        var chosen = new List<Piece>();
        var acks = new SortedDictionary<uint, AckPiece>();
        long used = 0;
        int maxSegment = MaxSegment;

        bool Fits(long size) => used + size <= capacity;

        // Takes an ARQ data D_PDU, merging the peer's ACK-ONLY into it when there is one to merge.
        bool TakeArq(ArqLink link, int length, Func<ArqFrame> frame)
        {
            int plain = DataOnlySize(link.Peer, length);
            if (acks.TryGetValue(link.Peer, out AckPiece? ack) && !ack.Merged && ack.Bitmap.Length <= ArqLink.MaxDataAckBytes)
            {
                int merged = DataAckSize(link.Peer, length, ack.Bitmap.Length);
                if (!Fits(merged - ack.Size))
                {
                    return false;   // DATA-ACK is smaller than DATA-ONLY plus ACK-ONLY, so neither fits
                }

                ack.Merged = true;
                used += merged - ack.Size;
                chosen.Add(new ArqPiece(link, frame(), merged, ack.Bitmap));
                return true;
            }

            if (!Fits(plain))
            {
                return false;
            }

            used += plain;
            chosen.Add(new ArqPiece(link, frame(), plain, null));
            return true;
        }

        foreach (ControlItem c in SortedControl())
        {
            // A misfit is skipped and the next one tried (core-architecture.md 5.3).
            if (Fits(c.Size))
            {
                chosenControl.Add(c);
                used += c.Size;
            }
        }

        foreach (Entry e in Expedited())
        {
            while (e.HasUnplacedSegment)
            {
                if (!e.Placed && !_expeditedIds.IsFree(_context.Now))
                {
                    break;
                }

                int size = SizeOf(e.NextSegmentLength(maxSegment), true, e.Dst);
                if (!Fits(size))
                {
                    break;   // skipped, the next expedited C_PDU is tried (core-architecture.md 5.3)
                }

                chosen.Add(TakeFirstCopy(e, maxSegment, _expeditedIds, size));
                used += size;
            }
        }

        foreach (ArqLink link in _links.Values)
        {
            if (!link.AckOwed || link.Suspended)
            {
                continue;   // C-0257
            }

            byte[] bitmap = link.AckBitmap();
            int size = AckOnlySize(link.Peer, bitmap.Length);
            if (Fits(size))
            {
                var ack = new AckPiece(link, size, bitmap);
                acks[link.Peer] = ack;
                chosen.Add(ack);
                used += size;
            }
        }

        foreach (ArqFrame f in FailedFrames())
        {
            TakeArq(_links[f.Owner.Peer], FrameLength(f), () => f);   // a misfit is skipped
        }

        bool stop = false;
        bool idFree() => _normalIds.IsFree(_context.Now);
        foreach (object c in DataCandidates())
        {
            if (c is Entry e)
            {
                if (HeldBehindExpedited(e.Dst, e.DstIsGroup))
                {
                    continue;   // held behind expedited data to the same destination (C-0615, C-0737, C-1044)
                }

                while (e.HasUnplacedSegment)
                {
                    int size = SizeOf(e.NextSegmentLength(maxSegment), false, e.Dst);
                    if ((!e.Placed && !idFree()) || !Fits(size))
                    {
                        stop = true;   // never let lower priority data overtake (C-0851); the rest waits (C-0880)
                        break;
                    }

                    chosen.Add(TakeFirstCopy(e, maxSegment, _normalIds, size));
                    used += size;
                }
            }
            else
            {
                var a = (ArqCPdu)c;
                if (!a.HasUnplacedSegment || LinkOf(a.Peer) is not ArqLink link || link.Suspended)
                {
                    continue;   // fully sent, its connection does not use the 16-bit family (P4-5), or a reset exchange is pending (C-0257)
                }

                bool started = a.Partial;
                while (a.HasUnplacedSegment)
                {
                    if (HeldBehindExpedited(a.Peer, false) || link.WindowSize >= MaxTxWindow)
                    {
                        // C-0775, C-1131: no new D_PDU now. A C_PDU not yet started is passed over;
                        // one already started stops the class, so nothing splits it (C-0850, C-1127).
                        stop = started;
                        break;
                    }

                    int length = a.Dropped ? 0 : a.NextSegmentLength(maxSegment);
                    if (!TakeArq(link, length, () => NewFrame(link, a, maxSegment)))
                    {
                        stop = true;   // C-0851, C-0880
                        break;
                    }

                    started = true;
                }
            }

            if (stop)
            {
                break;
            }
        }

        foreach (Entry e in Normal())
        {
            while (e.OwedRepeat() is int seg)
            {
                int size = SizeOf(e.Segments![seg].Length, false, e.Dst);
                if (!Fits(size))
                {
                    return (chosenControl, chosen);
                }

                e.Sent[seg]++;
                chosen.Add(new DataPiece(e, seg, e.Sent[seg], size));
                used += size;
            }
        }

        return (chosenControl, chosen);
    }

    /// <summary>Gives the next segment of an ARQ C_PDU an FSN (C-0189, C-0191, C-0510), cutting the C_PDU at its first placement (C-0502 to C-0509).</summary>
    private static ArqFrame NewFrame(ArqLink link, ArqCPdu a, int maxSegment)
    {
        if (!a.Placed)
        {
            a.Cut(maxSegment);
        }

        var frame = new ArqFrame(a, a.NextSegment, link.AllocateFsn());
        a.NextSegment++;
        a.Unacked++;
        link.Outstanding.Add(frame);
        return frame;
    }

    private Piece TakeFirstCopy(Entry e, int maxSegment, IdSpace ids, int size)
    {
        if (!e.Placed)
        {
            e.Place(ids.Allocate(), maxSegment);
        }

        int seg = e.FirstUnsent;
        e.Sent[seg] = 1;
        return new DataPiece(e, seg, 1, size);
    }

    /// <summary>
    /// The failed ARQ D_PDUs owed a retransmission, by priority, then the age of their C_PDU, then
    /// FSN order (C-0852, C-0853, C-0905, C-1132). Those to a peer with unsent expedited data wait
    /// for it (C-1131).
    /// </summary>
    private List<ArqFrame> FailedFrames()
    {
        var failed = new List<ArqFrame>();
        foreach (ArqLink link in _links.Values)
        {
            if (!HeldBehindExpedited(link.Peer, false) && !link.Suspended)   // C-0257
            {
                failed.AddRange(link.Outstanding.Where(f => f.State == ArqFrameState.Failed));
            }
        }

        failed.Sort((a, b) =>
            a.Owner.Priority != b.Owner.Priority ? b.Owner.Priority.CompareTo(a.Owner.Priority)
            : a.Owner.Seq != b.Owner.Seq ? a.Owner.Seq.CompareTo(b.Owner.Seq)
            : a.Segment.CompareTo(b.Segment));
        return failed;
    }

    /// <summary>
    /// The first transmissions of data, non-ARQ (type 7) entries and ARQ C_PDUs together: an ARQ
    /// C_PDU already partly sent first (C-0850, C-1127), then by priority, highest first, then age
    /// (C-0851, C-0853, C-0854).
    /// </summary>
    private List<object> DataCandidates()
    {
        var list = new List<(object Item, bool Partial, int Priority, long Seq)>();
        list.AddRange(Normal().Select(e => ((object)e, false, e.Priority, e.Seq)));
        list.AddRange(_arq.Select(a => ((object)a, a.Partial && _links.TryGetValue(a.Peer, out ArqLink? l) && !l.Suspended, a.Priority, a.Seq)));
        list.Sort((x, y) =>
            x.Partial != y.Partial ? y.Partial.CompareTo(x.Partial)
            : x.Priority != y.Priority ? y.Priority.CompareTo(x.Priority)
            : x.Seq.CompareTo(y.Seq));
        return list.Select(x => x.Item).ToList();
    }

    /// <summary>The segment length a frame carries: none once its C_PDU has been dropped (C-0182, C-0183).</summary>
    private static int FrameLength(ArqFrame f) => f.Owner.Dropped ? 0 : f.Owner.Segments![f.Segment].Length;

    private int MaxTxWindow => Math.Min(ArqLink.MaxWindowSize, _context.Config.Dts.MaxWindow);

    /// <summary>
    /// The byte capacity of this transmission (core-architecture.md 5.3): whole blocks within the
    /// smaller of 127.5 s and <c>dts.max_transmission_ms</c> (C-0106, K-0094, K-0095). If the first
    /// D_PDU the build would take does not fit, the transmission is made just long enough for it
    /// (C-0551, C-0878; C-1042): the limit never blocks one D_PDU, and nothing else stretches it.
    /// A D_PDU that needs more than 127.5 s on the configured waveform cannot be sent at all, which
    /// is a configuration the core cannot use.
    /// </summary>
    private long Capacity(BurstPlan shape, int first)
    {
        long blocks = BlocksWithin(shape, Budget);
        if (first <= blocks * shape.BytesPerBlock)
        {
            return blocks * shape.BytesPerBlock;
        }

        long needed = (first + shape.BytesPerBlock - 1) / shape.BytesPerBlock;
        if (shape.PreambleMs + (needed * shape.BlockMs) + shape.FlushMs > DtsConfig.MaxTransmissionLimitMs)
        {
            throw new ConfigException("drc.default_speed", $"a {first}-byte D_PDU needs more than 127.5 s on this waveform");
        }

        return needed * shape.BytesPerBlock;
    }

    private long Budget => Math.Min(DtsConfig.MaxTransmissionLimitMs, _context.Config.Dts.MaxTransmissionMs);

    private int MaxSegment => _context.Config.Dts.MaxSegmentSize;

    private static long BlocksWithin(BurstPlan shape, long budgetMs)
    {
        long room = budgetMs - shape.PreambleMs - shape.FlushMs;
        return room <= 0 ? 0 : room / shape.BlockMs;
    }

    /// <summary>
    /// Lays the chosen D_PDUs out (MANAGEMENT and WARNING first, P3-6; then first copies in the order
    /// chosen, then each round of repeats in the order chosen, C-1054) back to back with no pre-fill (D-0003), stamps EOT and the
    /// reception window, encodes, records each C_PDU's window commitment, and removes what owes
    /// nothing more.
    /// </summary>
    private Transmit Emit(List<ControlItem> chosenControl, List<Piece> chosen, Speed speed)
    {
        NodeConfig config = _context.Config;
        long now = _context.Now;
        var ordered = chosen.Where(p => p is not AckPiece { Merged: true }).Select((p, i) => (p, i)).ToList();
        ordered.Sort((a, b) => a.p.Copy != b.p.Copy ? a.p.Copy.CompareTo(b.p.Copy) : a.i.CompareTo(b.i));

        long total = chosenControl.Sum(c => (long)c.Size) + ordered.Sum(x => (long)x.p.Size);
        BurstPlan plan = _context.Modem.PlanBurst(speed.Wn, speed.Interleaver, (int)total);
        BurstPlan shape = _context.Modem.PlanBurst(speed.Wn, speed.Interleaver, 0);

        // The extra time each C_PDU's window must cover for copies left for later transmissions (C-1051).
        // Entries in the order they were first chosen; no dictionary is enumerated (core-architecture.md 6 rule 3).
        var owners = new List<Entry>();
        foreach (DataPiece p in chosen.OfType<DataPiece>())
        {
            if (!owners.Contains(p.Owner))
            {
                owners.Add(p.Owner);
                p.Owner.ExtraMs = LaterTransmissions(p.Owner, shape) * LaterTransmissionMs();
                p.Owner.NewCommitEnd = null;
            }
        }

        var bytes = new byte[total];
        long offset = 0;
        foreach (ControlItem c in chosenControl)
        {
            // EOT stamped as for data below (C-0104, C-0890, C-0891, C-1043).
            long block = offset / plan.BytesPerBlock;
            long airStart = plan.PreambleMs + (block * plan.BlockMs);
            int eot = (int)((plan.DurationMs - airStart + HalfSecondMs - 1) / HalfSecondMs);
            var header = Header(TakeEow(c.Dst, false), eot, c.Dst);
            byte[] encoded = DpduCodec.Encode(c.Build(header));
            if (encoded.Length != c.Size)
            {
                throw new InvalidOperationException("a D_PDU's size changed between planning and encoding");
            }

            encoded.CopyTo(bytes, offset);
            offset += encoded.Length;
            _control.Remove(c);
            c.Placed?.Invoke();
        }

        foreach ((Piece piece, int _) in ordered)
        {
            if (piece is not DataPiece p)
            {
                long arqBlock = offset / plan.BytesPerBlock;
                long arqStart = plan.PreambleMs + (arqBlock * plan.BlockMs);
                int arqEot = (int)((plan.DurationMs - arqStart + HalfSecondMs - 1) / HalfSecondMs);   // as below (C-0104, C-1043)
                byte[] arqBytes = EncodeArq(piece, arqEot);
                if (arqBytes.Length != piece.Size)
                {
                    throw new InvalidOperationException("a D_PDU's size changed between planning and encoding");
                }

                arqBytes.CopyTo(bytes, offset);
                offset += arqBytes.Length;
                continue;
            }

            Entry e = p.Owner;

            // Air start of the D_PDU: the start of the block holding its first byte (C-1043).
            // EOT counts from there to the planned end of the burst, which includes the flush
            // and the zero fill of the last block (C-0104, D-0005, D-0017), rounded up to the next
            // half second (C-0891); it cannot rise along the transmission (C-0890) and is at most
            // 255 because the burst is at most 127.5 s (C-0106).
            long block = offset / plan.BytesPerBlock;
            long airStart = plan.PreambleMs + (block * plan.BlockMs);
            int eot = (int)((plan.DurationMs - airStart + HalfSecondMs - 1) / HalfSecondMs);

            // The reception window runs from the D_PDU's start to the end of the last transmission
            // expected to carry part of the C_PDU (C-0350, C-0352, C-1051).
            int window = (int)Math.Min(MaxWindow, (plan.DurationMs - airStart + e.ExtraMs + HalfSecondMs - 1) / HalfSecondMs);
            long end = now + airStart + ((long)window * HalfSecondMs);
            e.NewCommitEnd = e.NewCommitEnd is long c ? Math.Min(c, end) : end;

            (int segOffset, int segLength) = e.Segments![p.Segment];
            var header = Header(TakeEow(e.Dst, e.DstIsGroup), eot, e.Dst);   // EOW 0, EMPTY (C-0398), unless one is owed (C-1079)
            var fields = new NonArqFields(
                e.Id,
                false,               // DELIVER IN ORDER is never set (C-0333)
                e.DstIsGroup,        // C-0338 to C-0340
                e.CPdu.Length,       // C-0343
                segOffset,           // C-0346, C-0347, C-0528, C-0529
                window);
            var segment = new Octets(e.CPdu.Span.Slice(segOffset, segLength));
            Dpdu pdu = e.Expedited
                ? new ExpeditedNonArqData(header, fields, segment, true)
                : new NonArqData(header, fields, segment, true);
            byte[] encoded = DpduCodec.Encode(pdu);
            if (encoded.Length != p.Size)
            {
                throw new InvalidOperationException("a D_PDU's size changed between planning and encoding");
            }

            encoded.CopyTo(bytes, offset);
            offset += encoded.Length;
        }

        foreach (Entry e in owners)
        {
            long end = e.NewCommitEnd!.Value;
            e.CommitEnd = end;   // no later copy may go out after this (C-0353, C-1052)
            (e.Expedited ? _expeditedIds : _normalIds).Hold(e.Id, end);   // the ID is not reused before it (C-0327, C-1053)
        }

        foreach (Entry e in owners)
        {
            if (e.Expedited && !e.HasUnplacedSegment && e.OwedRepeat() is null)
            {
                _sentExpedited.Add(e.Handle);   // confirmed at transmit_done (C-1100)
            }
        }

        _entries.RemoveAll(e => e.Placed && !e.HasUnplacedSegment && e.OwedRepeat() is null);
        return new Transmit(bytes, speed.Wn, speed.Interleaver, 7, true);
    }

    /// <summary>
    /// Encodes an ARQ D_PDU of this transmission. A data D_PDU carries its segment (none for a
    /// DROP PDU, C-0182, C-0183), C_PDU START and END for its place in the C_PDU (C-0176, C-0177,
    /// C-1124), the C_PDU's DELIVER IN ORDER (C-0178), and TX WIN UWE and TX WIN LWE when its FSN is
    /// the transmit window's upper or lower edge once this transmission's FSNs are allocated
    /// (C-0185, C-0186, C-1122). With the peer's acknowledgement merged it is a DATA-ACK carrying RX
    /// LWE and the bitmap (C-0238, C-0245 to C-0247, C-1007); otherwise DATA-ONLY. An ACK-ONLY
    /// carries RX LWE, bitmap encoding, offset 0 and the bitmap (C-0196 to C-0211, C-1128).
    /// </summary>
    private byte[] EncodeArq(Piece piece, int eot)
    {
        switch (piece)
        {
            case AckPiece a:
            {
                a.Link.AckOwed = false;
                var header = Header(TakeEow(a.Link.Peer, false), eot, a.Link.Peer);
                return DpduCodec.Encode(new AckOnly(header, a.Link.RxLwe, 0, 0, new Octets(a.Bitmap), null));
            }

            case ArqPiece d:
            {
                ArqLink link = d.Link;
                ArqFrame f = d.Frame;
                ArqCPdu owner = f.Owner;
                (int segOffset, int segLength) = owner.Segments![f.Segment];
                var segment = owner.Dropped ? Octets.Empty : new Octets(owner.Request.CPdu.Span.Slice(segOffset, segLength));
                var flags = new DataFlags(
                    f.Segment == 0,
                    f.Segment == owner.Segments.Count - 1,
                    owner.Request.DeliverInOrder,
                    owner.Dropped,
                    f.Fsn == link.TxUwe,
                    f.Fsn == link.TxLwe);
                var header = Header(TakeEow(link.Peer, false), eot, link.Peer);
                f.State = ArqFrameState.Awaiting;
                link.ArqUsed = true;
                _sentArqPeers.Add(link.Peer);
                if (d.AckBitmap is byte[] map)
                {
                    link.AckOwed = false;
                    return DpduCodec.Encode(new DataAck(header, flags, f.Fsn, link.RxLwe, 0, new Octets(map), segment, true));
                }

                return DpduCodec.Encode(new DataOnly(header, flags, f.Fsn, segment, true));
            }

            default:
                throw new InvalidOperationException($"unexpected piece {piece.GetType().Name}");
        }
    }

    private int DataOnlySize(uint dst, int segmentLength) =>
        DpduCodec.Encode(new DataOnly(Header(0, 0, dst), default, 0, new Octets(new byte[segmentLength]), true)).Length;

    private int DataAckSize(uint dst, int segmentLength, int ackBytes) =>
        DpduCodec.Encode(new DataAck(Header(0, 0, dst), default, 0, 0, 0, new Octets(new byte[ackBytes]), new Octets(new byte[segmentLength]), true)).Length;

    private int AckOnlySize(uint dst, int ackBytes) =>
        DpduCodec.Encode(new AckOnly(Header(0, 0, dst), 0, 0, 0, new Octets(new byte[ackBytes]), null)).Length;

    /// <summary>
    /// The EOW for the next D_PDU to an address: the one owed to that individual peer, used once, or
    /// EMPTY (C-0398, C-1079). Group and broadcast destinations always get EMPTY.
    /// </summary>
    private int TakeEow(uint dst, bool dstIsGroup)
    {
        if (dstIsGroup || !_owedEow.Remove(dst, out int eow))
        {
            return 0;
        }

        return eow;
    }

    /// <summary>
    /// How many more transmissions the copies this C_PDU still owes after this one need (C-1051):
    /// first copies of unsent segments, then repeats round by round, packed in that order into
    /// transmissions of the configured length; a copy larger than that length goes on its own.
    /// </summary>
    private int LaterTransmissions(Entry e, BurstPlan shape)
    {
        long room = BlocksWithin(shape, Budget) * shape.BytesPerBlock;
        int count = 0;
        long used = 0;
        foreach (int size in e.OwedSizes().Select(len => SizeOf(len, e.Expedited, e.Dst)))
        {
            if (count == 0 || used + size > room)
            {
                count++;
                used = 0;
            }

            used += size;
        }

        return count;
    }

    /// <summary>
    /// The acknowledgement wait when <c>dts.ack_wait_ms</c> is unset (C-1120): the longest the peer may
    /// wait before it transmits after hearing us, the longer LBT wait (K-0067, K-0077) plus the longest
    /// contention wait (K-0080), then a transmission of the configured length, by whose end a peer
    /// that heard us and shares our settings has answered unless it chose to send elsewhere.
    /// </summary>
    /// <summary>The time allowed for the peer to answer: <c>dts.ack_wait_ms</c>, or when unset <see cref="DerivedAckWaitMs"/> (C-1120); also the RESET/WIN-RESYNC wait (C-1172).</summary>
    public long AnswerWaitMs() => _context.Config.Dts.AckWaitMs ?? DerivedAckWaitMs();

    private long DerivedAckWaitMs()
    {
        CsmaConfig csma = _context.Config.Csma;
        return Budget + Math.Max(csma.LbtWaitDcdMs, csma.LbtWaitVdcdMs) + ((long)csma.NumContSlots * csma.ContSlotWidthMs);
    }

    /// <summary>
    /// The time allowed per later transmission in a reception window (C-1051; core-architecture.md
    /// 10 item 5): the configured transmission length, the LBT wait after an own transmission
    /// (K-0074; the common value in ed3 mode, K-0107) and the longest contention wait.
    /// </summary>
    private long LaterTransmissionMs()
    {
        CsmaConfig csma = _context.Config.Csma;
        long lbt = csma.RequireMode() == CsmaMode.Ed3 ? csma.LbtWaitDcdMs : csma.LbtWaitVdcdMs;
        return Budget + lbt + ((long)csma.NumContSlots * csma.ContSlotWidthMs);
    }

    /// <summary>
    /// Drops every queued C_PDU whose TTD is at or before now, in (TTD, arrival) order, and
    /// rejects each to the CAS with reason TTL expired (C-0857, C-0859, C-0864, C-1050). An ARQ C_PDU
    /// none of whose segments has an FSN is simply removed; one partly or wholly sent stays, marked
    /// dropped, so its D_PDUs not yet acknowledged go as DROP PDUs and the windows stay in step
    /// (C-0858, C-0860 to C-0862, C-1124).
    /// </summary>
    private void DropExpired()
    {
        var expired = _entries.Where(e => e.Ttd is long ttd && ttd <= _context.Now)
            .Select(e => (Ttd: e.Ttd!.Value, e.Seq, e.Request!, Entry: (Entry?)e, Arq: (ArqCPdu?)null))
            .Concat(_arq.Where(a => !a.Dropped && a.Request.Ttd <= _context.Now).Select(a => (a.Request.Ttd, a.Seq, a.Request, Entry: (Entry?)null, Arq: (ArqCPdu?)a)))
            .ToList();
        expired.Sort((a, b) => a.Ttd != b.Ttd ? a.Ttd.CompareTo(b.Ttd) : a.Seq.CompareTo(b.Seq));
        foreach ((long _, long _, DUnidataRequest request, Entry? e, ArqCPdu? a) in expired)
        {
            if (e is not null)
            {
                _entries.Remove(e);
            }
            else if (!a!.Placed)
            {
                _arq.Remove(a);
            }
            else
            {
                a.Dropped = true;
            }

            _context.Enqueue(new DUnidataRequestRejected(request.Handle, DReason.TtlExpired));
        }
    }

    /// <summary>
    /// Keeps <c>dts.ttd</c> at the earliest of: the TTDs in the queue, and for each ID space with
    /// an unplaced C_PDU waiting, the instant its next ID is freed (C-0327, C-1053). Started or
    /// restarted only when that instant changes, cancelled when there is none
    /// (core-architecture.md 3.2).
    /// </summary>
    private void ReconcileTimer()
    {
        long now = _context.Now;
        long? next = null;
        foreach (ArqCPdu a in _arq)
        {
            if (!a.Dropped)
            {
                next = next is long n ? Math.Min(n, a.Request.Ttd) : a.Request.Ttd;
            }
        }

        foreach (Entry e in _entries)
        {
            if (e.Ttd is long ttd)
            {
                next = next is long n ? Math.Min(n, ttd) : ttd;
            }

            IdSpace ids = e.Expedited ? _expeditedIds : _normalIds;
            if (!e.Placed && !ids.IsFree(now))
            {
                long freed = ids.NextFreedAt;
                next = next is long n ? Math.Min(n, freed) : freed;
            }
        }

        if (next is not long deadline)
        {
            _context.Timers.Cancel(TtdTimer);
            return;
        }

        if (_context.Timers.Deadline(TtdTimer) != deadline)
        {
            _context.Timers.Start(TtdTimer, deadline - now);
        }
    }

    /// <summary>An expedited C_PDU to the same destination is not yet fully placed (C-1044; for ARQ data C-1131).</summary>
    private bool HeldBehindExpedited(uint dst, bool dstIsGroup) =>
        _entries.Any(x => x.Expedited && x.HasUnplacedSegment && x.Dst == dst && x.DstIsGroup == dstIsGroup);

    private List<Entry> Expedited()
    {
        List<Entry> list = _entries.Where(e => e.Expedited).ToList();
        list.Sort((a, b) => a.Seq.CompareTo(b.Seq));
        return list;
    }

    private List<Entry> Normal()
    {
        List<Entry> list = _entries.Where(e => !e.Expedited).ToList();
        list.Sort((a, b) => a.Priority != b.Priority ? b.Priority.CompareTo(a.Priority) : a.Seq.CompareTo(b.Seq));
        return list;
    }

    /// <summary>The encoded size of a type 7 or 8 D_PDU with a segment of this length; EOT and window values do not change it.</summary>
    private int SizeOf(int segmentLength, bool expedited, uint dst)
    {
        DpduHeader header = Header(0, 0, dst);
        var fields = new NonArqFields(0, false, false, segmentLength, 0, 0);
        var segment = new Octets(new byte[segmentLength]);
        Dpdu pdu = expedited ? new ExpeditedNonArqData(header, fields, segment, true) : new NonArqData(header, fields, segment, true);
        return DpduCodec.Encode(pdu).Length;
    }

    /// <summary>
    /// A header from this node to <paramref name="dst"/>, with the smallest address size that holds both
    /// addresses (C-0133, C-0130, C-0108, C-0109): so a group or broadcast destination, or any
    /// address wider than our own, gets the size it needs, up to 7 for the broadcast address (C-0123).
    /// </summary>
    private DpduHeader Header(int eow, int eot, uint dst)
    {
        uint src = _context.Config.LocalAddress;
        return new DpduHeader(eow, eot, DpduAddress.MinimumSize(dst, src), dst, src);
    }

    /// <summary>One D_PDU chosen for a transmission, with its encoded size.</summary>
    private abstract class Piece(int size)
    {
        public int Size { get; } = size;

        /// <summary>The copy number for the round order of non-ARQ repeats (C-1054); 1 for everything else.</summary>
        public virtual int Copy => 1;
    }

    /// <summary>A non-ARQ D_PDU: a copy (1 = first) of one segment of a C_PDU.</summary>
    private sealed class DataPiece(Entry owner, int segment, int copy, int size) : Piece(size)
    {
        public Entry Owner { get; } = owner;

        public int Segment { get; } = segment;

        public override int Copy => copy;
    }

    /// <summary>An ACK-ONLY to a peer, with the bitmap fixed at selection. Merged: a DATA-ACK carries it instead.</summary>
    private sealed class AckPiece(ArqLink link, int size, byte[] bitmap) : Piece(size)
    {
        public ArqLink Link { get; } = link;

        public byte[] Bitmap { get; } = bitmap;

        public bool Merged { get; set; }
    }

    /// <summary>An ARQ data D_PDU, first transmission or retransmission; with an acknowledgement bitmap it goes as DATA-ACK.</summary>
    private sealed class ArqPiece(ArqLink link, ArqFrame frame, int size, byte[]? ackBitmap) : Piece(size)
    {
        public ArqLink Link { get; } = link;

        public ArqFrame Frame { get; } = frame;

        public byte[]? AckBitmap { get; } = ackBitmap;
    }

    /// <summary>
    /// One C_PDU ID space (C-0326, C-0328): the next ID, allocated in ascending order modulo 4096
    /// from 0 (C-1040), and for each ID the end of the last reception window announced for the
    /// C_PDU that had it, before which it is not reused (C-0327, C-1053).
    /// </summary>
    private sealed class IdSpace
    {
        private readonly long[] _heldUntil = Enumerable.Repeat(long.MinValue, CPduIdModulus).ToArray();
        private int _next;

        /// <summary>The instant the next ID is free.</summary>
        public long NextFreedAt => _heldUntil[_next];

        public bool IsFree(long now) => _heldUntil[_next] <= now;

        public int Allocate()
        {
            int id = _next;
            _heldUntil[id] = long.MaxValue;   // in use until its window is known, at the end of the build
            _next = (_next + 1) % CPduIdModulus;
            return id;
        }

        /// <summary>Holds the ID to the latest window end announced for its C_PDU.</summary>
        public void Hold(int id, long until) =>
            _heldUntil[id] = _heldUntil[id] == long.MaxValue ? until : Math.Max(_heldUntil[id], until);
    }

    private sealed class Entry(long seq, bool expedited, int priority, uint dst, bool dstIsGroup, ReadOnlyMemory<byte> cpdu,
                               DUnidataRequest? request, long? ttd, int copies)
    {
        public long Seq { get; } = seq;

        public bool Expedited { get; } = expedited;

        public int Priority { get; } = priority;

        public uint Dst { get; } = dst;

        public bool DstIsGroup { get; } = dstIsGroup;

        public ReadOnlyMemory<byte> CPdu { get; } = cpdu;

        public DUnidataRequest? Request { get; } = request;

        /// <summary>The request handle of an expedited entry (C-1100).</summary>
        public int Handle { get; init; }

        /// <summary>TimeToDie, absolute core ms; none for expedited requests.</summary>
        public long? Ttd { get; } = ttd;

        /// <summary>How many times each D_PDU is sent: the retransmission count plus one (A-0083).</summary>
        public int Copies { get; } = copies;

        /// <summary>The segments (offset, length), cut at first placement; null until then.</summary>
        public List<(int Offset, int Length)>? Segments { get; private set; }

        /// <summary>Copies of each segment placed so far.</summary>
        public int[] Sent { get; private set; } = [];

        public int Id { get; private set; }

        /// <summary>The end of the reception window last announced; later copies must end before it (C-1052).</summary>
        public long? CommitEnd { get; set; }

        /// <summary>Build scratch: the window time owed to later transmissions (C-1051).</summary>
        public long ExtraMs { get; set; }

        /// <summary>Build scratch: the earliest window end stamped on this C_PDU in the transmission being built.</summary>
        public long? NewCommitEnd { get; set; }

        public bool Placed => Segments is not null;

        /// <summary>The first segment never sent; segments are first sent in order.</summary>
        public int FirstUnsent => Array.IndexOf(Sent, 0);

        public bool HasUnplacedSegment => !Placed || FirstUnsent >= 0;

        /// <summary>The length of the next first-copy segment, cutting with this size if not yet cut.</summary>
        public int NextSegmentLength(int maxSegment) =>
            Placed ? Segments![FirstUnsent].Length : Math.Min(maxSegment, CPdu.Length);

        /// <summary>Cuts the C_PDU into segments (C-0525 to C-0529) and takes its ID (C-0326).</summary>
        public void Place(int id, int maxSegment)
        {
            Id = id;
            var segments = new List<(int, int)>();
            for (int offset = 0; offset < CPdu.Length; offset += maxSegment)
            {
                segments.Add((offset, Math.Min(maxSegment, CPdu.Length - offset)));
            }

            Segments = segments;
            Sent = new int[segments.Count];
        }

        /// <summary>The next repeat owed, lowest copy first, then segment order; null when none.</summary>
        public int? OwedRepeat()
        {
            if (!Placed)
            {
                return null;
            }

            int best = -1;
            for (int j = 0; j < Sent.Length; j++)
            {
                if (Sent[j] > 0 && Sent[j] < Copies && (best < 0 || Sent[j] < Sent[best]))
                {
                    best = j;
                }
            }

            return best < 0 ? null : best;
        }

        /// <summary>The segment lengths of every copy still owed, in the order later builds would place them (C-1051).</summary>
        public IEnumerable<int> OwedSizes()
        {
            if (!Placed)
            {
                yield break;
            }

            foreach (int j in Enumerable.Range(0, Sent.Length).Where(j => Sent[j] == 0))
            {
                yield return Segments![j].Length;
            }

            for (int round = 2; round <= Copies; round++)
            {
                for (int j = 0; j < Sent.Length; j++)
                {
                    if (Math.Max(Sent[j], 1) < round)
                    {
                        yield return Segments![j].Length;
                    }
                }
            }
        }
    }
